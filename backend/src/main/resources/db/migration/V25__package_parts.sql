-- A package can hold several simulations: a programme of parts (D62).
--
-- The class list stays at package level — same companies, same seats in every part — and each part
-- carries its own template (frozen when the package is published, like any other). Rounds come from
-- the part's template; state does not carry between parts, which keeps the parts comparable: every
-- company starts each part from the same opening condition, so the difference between parts is skill,
-- not inheritance.

create table simulation_package_part (
    id                  bigint generated by default as identity primary key,
    package_id          bigint       not null references simulation_package (id) on delete cascade,
    position            integer      not null check (position >= 1),
    name                varchar(200) not null,
    -- The part's template is a frozen scenario owned by this package: when the scenario goes (package
    -- retired and tidied, tenant removed, test cleanup), the part goes with it. Without the cascade a
    -- scenario delete deadlocks against its own edge cases and every cleanup order becomes load-bearing.
    template_key        varchar(60)  not null references scenario (key) on delete cascade,
    source_template_key varchar(60)  references scenario (key) on delete set null,
    template_version    integer      not null,
    created_at          timestamptz  not null default now(),
    unique (package_id, position)
);

create index simulation_package_part_package on simulation_package_part (package_id, position);

-- Every package published so far is a one-part programme: the parts table is the general case, the
-- package's own template columns stay as "part 1" so existing screens and reports keep working.
insert into simulation_package_part
    (package_id, position, name, template_key, source_template_key, template_version)
select id, 1, name, template_key, source_template_key, template_version
from simulation_package;

-- Which part a run is. Null for runs started outside a package.
alter table run add column if not exists part_position integer;

update run set part_position = 1 where package_id is not null;

comment on column run.part_position is
    'D62: which part of its package this run plays; null when the run has no package';
