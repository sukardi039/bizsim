-- Auto workers (D47–D50): a company can be run by a policy instead of a person.
--
-- Four things, and nothing that touches an existing row:
--   1. a fifth role, so a bot person is a first-class identity — it signs decisions, it can be
--      seated, and it can never log in;
--   2. bot_profile, the reusable brain a builder owns: level (how well it plays) × personality
--      (what it wants), versioned so a change next term cannot rewrite what happened last term;
--   3. player.bot_profile_id, which is what makes a *seat* a bot seat — the brain lives with the
--      seat, so moving a company to a person is a data change, not a code change;
--   4. bot_decision, the trace: which profile version, which seed, which context, what it decided
--      and why, and how it got there (scheduled, replayed by hand, or never — a no-plan month).
--
-- Nothing here changes how a round computes: a bot submits through the same path as a trainee.

alter table app_user drop constraint if exists app_user_role_check;

alter table app_user add constraint app_user_role_check
    check (role in ('ADMIN', 'FACILITATOR', 'BUILDER', 'PLAYER', 'AUTO_WORKER'));

comment on column app_user.role is
    'ADMIN = both jobs; BUILDER = prepares packages; FACILITATOR = runs sessions; '
    'PLAYER = trainee; AUTO_WORKER = a company played by a policy, never logs in';

-- A bot account holds an unusable password hash and is refused at login (see AuthController).
alter table app_user add column if not exists bot_profile_id bigint;

create table bot_profile (
    id          bigint generated by default as identity primary key,
    tenant_id   bigint      not null references tenant (id) on delete cascade,
    key         varchar(60) not null,
    name        varchar(120) not null,
    level       varchar(10) not null check (level in ('LOW', 'MID', 'HIGH')),
    personality varchar(12) not null check (personality in ('CAUTIOUS', 'BALANCED', 'AGGRESSIVE')),
    -- The knobs the policy reads. Kept as a document so a new knob is not a migration.
    params      jsonb       not null default '{}'::jsonb,
    -- Bumped on every edit; a decision records the version that produced it.
    version     integer     not null default 1,
    active      boolean     not null default true,
    -- A builder leaving the tenant must not take the library with them.
    created_by  bigint references app_user (id) on delete set null,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now(),
    unique (tenant_id, key)
);

create index bot_profile_tenant_idx on bot_profile (tenant_id, active);

alter table app_user add constraint app_user_bot_profile_fk
    foreign key (bot_profile_id) references bot_profile (id);

-- The brain belongs to the seat: a company is auto-played iff its seat carries a profile.
alter table player add column if not exists bot_profile_id bigint references bot_profile (id);

comment on column player.bot_profile_id is
    'Non-null = this seat is played by a policy. The person row is still the identity that signs decisions.';

create table bot_decision (
    id              bigint generated by default as identity primary key,
    round_id        bigint      not null references round (id) on delete cascade,
    team_id         bigint      not null references team (id) on delete cascade,
    profile_key     varchar(60) not null,
    profile_version integer     not null,
    -- A snapshot, not a pointer: replay must work after the profile is edited.
    params          jsonb       not null,
    params_digest   varchar(64) not null,
    seed_key        varchar(200) not null,
    context_digest  varchar(64) not null,
    rationale       text,
    -- SCHEDULED = the worker submitted during the round; MANUAL = a facilitator asked it to;
    -- NONE = the round closed with no decision (the company ran on its standing plan, like a person).
    mode            varchar(10) not null check (mode in ('SCHEDULED', 'MANUAL', 'NONE')),
    decided_at      timestamptz not null default now(),
    unique (round_id, team_id)
);

create index bot_decision_round_idx on bot_decision (round_id);

-- The mechanic is a per-template switch, like quality (D40): absent = off, so every existing
-- template, package and copy keeps playing exactly the companies it has today.
update scenario
set definition = definition || '{"autoWorkers": false}'::jsonb
where key = 'standard-v1' and not (definition ? 'autoWorkers');
