-- Simulation packages: the boundary between building and running (ruling of 3 Nov 2026).
--
-- "Building the simulation package and the execution of the simulation package are two separate
-- functions, performed by two parties; preparation has to be done well before the facilitator
-- executes it." Until now a session was started from whatever the facilitator happened to have
-- lying around: a template key, some profiles, a couple of names. This table makes the prepared
-- thing a first-class, nameable, publishable artefact.
--
-- A package is **immutable once published**: it records the template *version* it was built on and
-- the profiles it contains, so a builder editing a template afterwards cannot change a session that
-- was already sold to a class. Retiring is a status change, not a delete — a package that ran a
-- cohort is history.
--
-- The tenant owns packages. The shipped template stays global, but a package always belongs to the
-- organisation that will run it.

create table simulation_package (
    id                   bigint generated by default as identity primary key,
    tenant_id            bigint       not null references tenant (id) on delete cascade,
    name                 varchar(200) not null,
    template_key         varchar(60)  not null references scenario (key),
    template_version     integer      not null,
    company_profile_ids  jsonb        not null default '[]'::jsonb,
    status               varchar(20)  not null default 'PUBLISHED'
                             check (status in ('PUBLISHED', 'RETIRED')),
    published_at         timestamptz  not null default now(),
    published_by         bigint       references app_user (id) on delete set null
);

create index simulation_package_tenant_idx on simulation_package (tenant_id);

comment on table simulation_package is
    'A prepared, immutable bundle (template version + company profiles) a facilitator runs sessions from';
comment on column simulation_package.template_version is
    'the scenario.version at publish time: proves which economy the package was built on';

-- Which package a cohort was run from: the facilitator's audit trail, and the reason a package can be
-- retired but not deleted.
alter table run add column package_id bigint references simulation_package (id) on delete set null;
