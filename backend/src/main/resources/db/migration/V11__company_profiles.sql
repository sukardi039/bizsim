-- Company profiles: the reusable definition of a company (S6e, ruling of 3 Nov 2026).
--
-- "one global and reusable, extendable and reusable by other simulations". Same shape as templates:
-- a global base row (tenant_id null) that any tenant may copy and adapt, and tenant-owned rows that
-- belong to one organisation.
--
-- A profile is *who the company is*: its display name and which products of the template it carries.
-- The economy — starting cash, brand, staff, prices — stays with the template, so a profile is worth
-- reusing across templates and a template is worth reusing across cohorts. `products` is an array of
-- product codes; an empty array means the template's full line.

create table company_profile (
    id           bigint generated by default as identity primary key,
    tenant_id    bigint references tenant (id) on delete cascade,
    name         varchar(120) not null,
    company_name varchar(200) not null default '',
    products     jsonb        not null default '[]'::jsonb,
    notes        varchar(500),
    based_on     bigint references company_profile (id),
    created_at   timestamptz  not null default now()
);

create index company_profile_tenant_idx on company_profile (tenant_id);

comment on column company_profile.tenant_id is
    'null = the shipped profile every tenant can use; set = a profile owned by that tenant';
comment on column company_profile.products is
    'array of product codes from the template; empty = every product of the template';

