-- D12/Q-G: the facilitator's four powers that were ruled but not built -- pause and extend the
-- round clock, a reasoned cash adjustment, voiding the last computed round -- plus the snapshot
-- that makes a void honest (you cannot restore a month you did not record), and the quality
-- upgrade mechanic (D15) that needs one statement line to name its money.

-- The clock: `closes_at` is the deadline; while `paused_at` is set the deadline is frozen and the
-- round clock sweep skips the row.
alter table round add column paused_at timestamptz;

-- Every deliberate hand on the simulation, in the order it happened. A class dispute ("why did our
-- cash jump?") is answered by this table, not by a memory of the class day.
create table facilitator_action (
    id           bigint generated by default as identity primary key,
    tenant_id    bigint       not null references tenant (id) on delete cascade,
    run_id       bigint       not null references run (id) on delete cascade,
    round_number integer,
    team_id      bigint       references team (id) on delete set null,
    action       varchar(24)  not null
                 check (action in ('CLOCK_PAUSE', 'CLOCK_RESUME', 'CLOCK_EXTEND', 'CASH_ADJUST', 'ROUND_VOID')),
    amount       numeric(14, 2),
    reason       text,
    actor_id     bigint       not null references app_user (id),
    created_at   timestamptz  not null default now()
);

create index facilitator_action_run on facilitator_action (run_id, id);

-- What every company looked like when the round was computed. Voiding a round restores this
-- instead of trying to invert the engine: brand, staff, machine workers and the R&D slate are all
-- state the statement does not carry, so a reversal would have to guess.
create table round_snapshot (
    round_id bigint not null references round (id) on delete cascade,
    team_id  bigint not null references team (id) on delete cascade,
    state    jsonb  not null,
    primary key (round_id, team_id)
);

-- D15: quality upgrades are money spent this month, so the statement names the line rather than
-- hiding it inside another cost.
alter table round_statement add column quality_cost numeric(14, 2) not null default 0;

-- The shipped template demonstrates the mechanic; every template that does not carry the switch
-- keeps today's behaviour (absent = off).
update scenario
set definition = definition
    || '{"qualityUpgrade": true, "qualityCostPerPoint": 60000000}'::jsonb
where key = 'standard-v1';
