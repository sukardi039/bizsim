-- V1 baseline: the ten core tables of the simulation.
--
-- Rules encoded here on purpose:
--   * every business table carries tenant_id (decision B: hosted multi-tenant)
--   * round_result is written only by the server (decision A)
--   * decision.payload is client input, never trusted as canonical state
--   * ids are identity bigints; no natural keys leak across tenants

create table tenant (
    id          bigint generated by default as identity primary key,
    code        varchar(40)  not null unique,
    name        varchar(200) not null,
    created_at  timestamptz  not null default now()
);

create table app_user (
    id            bigint generated by default as identity primary key,
    tenant_id     bigint       not null references tenant (id) on delete cascade,
    email         varchar(320) not null,
    password_hash varchar(100) not null,
    display_name  varchar(200) not null,
    role          varchar(20)  not null check (role in ('ADMIN', 'FACILITATOR', 'PLAYER')),
    active        boolean      not null default true,
    created_at    timestamptz  not null default now(),
    -- Same email may exist in two tenants; it must be unique inside one.
    unique (tenant_id, email)
);
create index app_user_tenant_idx on app_user (tenant_id);

-- A shipped, versioned scenario definition. Read-only in v1 (decision E).
create table scenario (
    key             varchar(60) primary key,
    name            varchar(200) not null,
    definition      jsonb        not null,
    version         integer      not null default 1,
    created_at      timestamptz  not null default now()
);

create table simulation (
    id             bigint generated by default as identity primary key,
    tenant_id      bigint       not null references tenant (id) on delete cascade,
    name           varchar(200) not null,
    scenario_key   varchar(60)  not null references scenario (key),
    status         varchar(20)  not null default 'DRAFT'
                   check (status in ('DRAFT', 'READY', 'ARCHIVED')),
    facilitator_id bigint       not null references app_user (id),
    created_at     timestamptz  not null default now()
);
create index simulation_tenant_idx on simulation (tenant_id);

-- One execution of a simulation (a class running it this week).
create table run (
    id             bigint generated by default as identity primary key,
    tenant_id      bigint       not null references tenant (id) on delete cascade,
    simulation_id  bigint       not null references simulation (id) on delete cascade,
    scenario_key   varchar(60)  not null references scenario (key),
    status         varchar(20)  not null default 'DRAFT'
                   check (status in ('DRAFT', 'OPEN', 'FINISHED', 'ABANDONED')),
    current_round  integer      not null default 0,
    started_at     timestamptz,
    finished_at    timestamptz,
    created_at     timestamptz  not null default now()
);
create index run_tenant_idx on run (tenant_id);

create table team (
    id           bigint generated by default as identity primary key,
    run_id       bigint       not null references run (id) on delete cascade,
    name         varchar(120) not null,
    company_name varchar(200) not null,
    cash         numeric(14, 2) not null default 0,
    brand_score  numeric(6, 2)  not null default 50,
    unique (run_id, name)
);

create table player (
    id       bigint generated by default as identity primary key,
    run_id   bigint      not null references run (id) on delete cascade,
    team_id  bigint      not null references team (id) on delete cascade,
    user_id  bigint      not null references app_user (id),
    role_key varchar(40) not null,
    unique (run_id, user_id)
);

create table round (
    id         bigint generated by default as identity primary key,
    run_id     bigint      not null references run (id) on delete cascade,
    number     integer     not null,
    status     varchar(20) not null default 'OPEN'
               check (status in ('OPEN', 'CLOSED', 'COMPUTED')),
    opened_at  timestamptz not null default now(),
    closed_at  timestamptz,
    unique (run_id, number)
);

-- What a team asked for. One row per team+role+round; idempotent on that key.
create table decision (
    id           bigint generated by default as identity primary key,
    round_id     bigint      not null references round (id) on delete cascade,
    team_id      bigint      not null references team (id) on delete cascade,
    role_key     varchar(40) not null,
    payload      jsonb       not null,
    submitted_at timestamptz not null default now(),
    submitted_by bigint      not null references app_user (id),
    unique (round_id, team_id, role_key)
);

-- Server-computed. Never written from a client payload directly.
create table round_result (
    id           bigint generated by default as identity primary key,
    round_id     bigint        not null references round (id) on delete cascade,
    team_id      bigint        not null references team (id) on delete cascade,
    score        jsonb         not null,
    total_score  numeric(12, 2) not null,
    computed_at  timestamptz   not null default now(),
    unique (round_id, team_id)
);
